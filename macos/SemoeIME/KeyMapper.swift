import AppKit
import SemoeFFI

/// macOS 가상 키 코드 → SemoeKey(USB HID usage). 물리 자리 기준이라 시스템 영문 배열과 무관하다.
enum KeyMapper {
    private static let hidUsage: [UInt16: UInt16] = [
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, // a b c d e f
        0x05: 0x0A, 0x04: 0x0B, 0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, // g h i j k l
        0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13, 0x0C: 0x14, 0x0F: 0x15, // m n o p q r
        0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B, // s t u v w x
        0x10: 0x1C, 0x06: 0x1D,                                                 // y z
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22,             // 1 2 3 4 5
        0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25, 0x19: 0x26, 0x1D: 0x27,             // 6 7 8 9 0
        0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,             // ⏎ esc ⌫ ⇥ space
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31,             // - = [ ] \
        0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38, // ; ' ` , . /
        0x0A: 0x64,                                                             // ISO §
        0x4F: 0x6D,                                                             // F18
    ]

    static func key(for keyCode: UInt16) -> UInt16 {
        hidUsage[keyCode] ?? 0
    }

    static func modifiers(_ flags: NSEvent.ModifierFlags) -> UInt32 {
        var m: UInt32 = 0
        if flags.contains(.shift) { m |= UInt32(SEMOE_MOD_SHIFT) }
        if flags.contains(.capsLock) { m |= UInt32(SEMOE_MOD_CAPS) }
        if flags.contains(.control) { m |= UInt32(SEMOE_MOD_CTRL) }
        if flags.contains(.option) { m |= UInt32(SEMOE_MOD_ALT) }
        if flags.contains(.command) { m |= UInt32(SEMOE_MOD_CMD) }
        return m
    }
}
